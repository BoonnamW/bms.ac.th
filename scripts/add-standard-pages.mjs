// เพิ่มหน้ามาตรฐานที่เว็บไซต์หน่วยงานภาครัฐ/สถานศึกษาควรมี — รันซ้ำได้ ไม่ทับเนื้อหาที่แก้ไขแล้วในหลังบ้าน
// อ้างอิง: แบบตรวจการเปิดเผยข้อมูลสาธารณะ (OIT) ตามการประเมิน ITA ของสำนักงาน ป.ป.ช. และมาตรฐานเว็บไซต์ภาครัฐของ สพร. (DGA)
import { db } from '../lib/db.js';
import { OIT, OIT_GROUP, oitSort } from '../lib/oit.js';

if (db.prepare("SELECT 1 FROM settings WHERE key='standard_pages_added'").get()) {
  console.log('เพิ่มหน้ามาตรฐานไปแล้ว — ข้าม');
  process.exit(0);
}

const upPage = db.prepare(`INSERT INTO pages (title,slug,menu_group,body,in_menu,sort,published) VALUES (?,?,?,?,?,?,1)
  ON CONFLICT(slug) DO NOTHING`); // ถ้ามีหน้านี้อยู่แล้ว (เช่น เจ้าหน้าที่แก้ไขไปแล้ว) จะไม่ทับ

// ---------- นโยบายความเป็นส่วนตัว (PDPA) ----------
upPage.run('นโยบายความเป็นส่วนตัว', 'privacy-policy', null,
  '<p>เว็บไซต์นี้เก็บรวบรวมข้อมูลส่วนบุคคลเท่าที่จำเป็นสำหรับการติดต่อกลับผ่านแบบฟอร์มติดต่อเราเท่านั้น ได้แก่ ชื่อ อีเมล เบอร์โทรศัพท์ และข้อความที่ท่านกรอก</p>' +
  '<h3>วัตถุประสงค์การใช้ข้อมูล</h3><p>เพื่อติดต่อกลับและตอบข้อสอบถามที่เกี่ยวข้องกับโรงเรียนเท่านั้น โรงเรียนจะไม่นำข้อมูลไปใช้เพื่อวัตถุประสงค์อื่น และไม่เปิดเผยต่อบุคคลภายนอก เว้นแต่ได้รับความยินยอมหรือเป็นไปตามที่กฎหมายกำหนด</p>' +
  '<h3>ระยะเวลาการเก็บข้อมูล</h3><p>โรงเรียนจะเก็บข้อมูลไว้เท่าที่จำเป็นต่อการดำเนินการตามวัตถุประสงค์ข้างต้น</p>' +
  '<h3>สิทธิของเจ้าของข้อมูล</h3><p>ท่านมีสิทธิขอเข้าถึง แก้ไข หรือขอให้ลบข้อมูลส่วนบุคคลของท่านได้ โดยติดต่อโรงเรียนผ่านช่องทางที่แจ้งไว้ในหน้าติดต่อเรา</p>' +
  '<h3>คุกกี้ (Cookies)</h3><p>เว็บไซต์ใช้คุกกี้เท่าที่จำเป็นต่อการทำงานของระบบ (เช่น การยืนยันตัวตนของเจ้าหน้าที่ และการป้องกันการปลอมแปลงคำขอ) เท่านั้น ไม่ใช้คุกกี้เพื่อการติดตามพฤติกรรมหรือโฆษณา</p>' +
  '<p><small>นโยบายนี้เป็นแม่แบบเบื้องต้นตามพระราชบัญญัติคุ้มครองข้อมูลส่วนบุคคล พ.ศ. 2562 (PDPA) ขอแนะนำให้เจ้าหน้าที่คุ้มครองข้อมูลของโรงเรียนตรวจสอบและปรับให้ตรงตามแนวปฏิบัติจริงก่อนเผยแพร่</small></p>',
  0, 0);

// ---------- เปิดเผยข้อมูลสาธารณะ (OIT) — ตามแบบประเมิน ITA สำหรับสถานศึกษา สังกัด สพฐ. ----------
const holder = (label) => `<p>อยู่ระหว่างจัดเตรียมข้อมูล — เจ้าหน้าที่สามารถแก้ไขหน้านี้และแนบเอกสารได้จากเมนู "หน้าเว็บไซต์" ในหลังบ้าน</p><p><small>รายการนี้เป็นส่วนหนึ่งของแบบตรวจการเปิดเผยข้อมูลสาธารณะ (OIT): ${label}</small></p>`;
OIT.forEach(([code, label]) => upPage.run(label, `oit-${code}`, OIT_GROUP, holder(label), 1, oitSort(code)));

// ---------- E-Service (ลิงก์ด่วนไปหน้าติดต่อ/ดาวน์โหลดเอกสาร) ----------
db.prepare("UPDATE links SET title=?, icon=?, url=? WHERE title='ติดต่อเรา'").run('ช่องทางร้องเรียน', 'phone', '/contact');

db.prepare("INSERT INTO settings (key,value) VALUES ('standard_pages_added','1') ON CONFLICT(key) DO UPDATE SET value=excluded.value").run();
console.log(`✓ เพิ่มหน้านโยบายความเป็นส่วนตัว และหน้าเปิดเผยข้อมูล (ITA) ${OIT.length} รายการ`);
