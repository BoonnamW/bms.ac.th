let offline = false; // ถ้าโหลดรูปครั้งแรกไม่ได้ (เว็บต้นทางไม่ตอบ/บล็อก) ให้ข้ามรูปที่เหลือ เพื่อไม่ให้เซิร์ฟเวอร์เริ่มช้า
async function download(file) {
  if (!file || offline) return null;
  try {
    const res = await fetch(BASE + file, { headers: { 'User-Agent': 'Mozilla/5.0' }, signal: AbortSignal.timeout(8000) });
    if (!res.ok) throw new Error(res.status);
    const buf = Buffer.from(await res.arrayBuffer());
    const ext = detectImage(buf);
    if (!ext || buf.length > 8 * 1024 * 1024) throw new Error('ไม่ใช่รูปที่รองรับหรือใหญ่เกินไป');
    const name = `${crypto.randomBytes(16).toString('hex')}.${ext}`;
    fs.writeFileSync(path.join(UPLOAD_DIR, name), buf);
    return name;
  } catch (e) {
    console.warn(`  ! โหลดรูปไม่สำเร็จ ${file}: ${e.message}`);
    if (/abort|timeout|fetch failed|403|429/i.test(String(e.message)) || e.name === 'TimeoutError') offline = true;
    return null;
  }
}

